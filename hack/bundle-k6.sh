#!/usr/bin/env bash
# Bundle k6 test scripts with their lib dependency into self-contained files.
#
# The k6 operator references a single ConfigMap key per TestRun, so a script
# cannot import ../lib/ipam-client.js at run time. For each script in
# test/load/src/ this:
#   - drops its import of ../lib/ipam-client.js,
#   - merges the remaining k6 imports with the lib's own (one import statement
#     per module, so a name both files import is not declared twice),
#   - writes imports + lib body + script body to
#     config/components/k6-performance-tests/generated/<name>.js.
# Stale bundles whose source was deleted are removed.
#
# Run via: task test/load:generate

set -euo pipefail

ROOT_DIR="${ROOT_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
SRC_DIR="${ROOT_DIR}/test/load/src"
LIB_FILE="${ROOT_DIR}/test/load/lib/ipam-client.js"
DEST_DIR="${DEST_DIR:-${ROOT_DIR}/config/components/k6-performance-tests/generated}"

if [ ! -f "${LIB_FILE}" ]; then
  echo "ERROR: lib file not found at ${LIB_FILE}" >&2
  exit 1
fi

mkdir -p "${DEST_DIR}"
rm -f "${DEST_DIR}"/*.js

python3 - "${LIB_FILE}" "${SRC_DIR}" "${DEST_DIR}" <<'PY'
import os
import re
import sys

lib_path, src_dir, dest_dir = sys.argv[1:4]

IMPORT_RE = re.compile(
    r"^import\s+(?P<what>[^;]*?)\s+from\s+'(?P<mod>[^']+)';[ \t]*\n",
    re.MULTILINE | re.DOTALL,
)


def split_imports(src):
    """Return ([(what, module)], body without the import statements)."""
    imports = [(m.group('what'), m.group('mod')) for m in IMPORT_RE.finditer(src)]
    return imports, IMPORT_RE.sub('', src)


def merge(imports):
    """Merge import clauses per module: {module: (default or None, {named})}."""
    out = {}
    for what, mod in imports:
        default, named = out.get(mod, (None, set()))
        what = what.strip()
        m = re.match(r'^(?:(\w+)\s*,?\s*)?(?:\{([^}]*)\})?$', what, re.DOTALL)
        if not m:
            raise SystemExit(f"unsupported import clause: import {what} from '{mod}'")
        if m.group(1):
            if default and default != m.group(1):
                raise SystemExit(f"conflicting default imports from {mod}: {default}, {m.group(1)}")
            default = m.group(1)
        if m.group(2):
            named |= {n.strip() for n in m.group(2).split(',') if n.strip()}
        out[mod] = (default, named)
    return out


def render(merged):
    lines = []
    for mod in sorted(merged):
        default, named = merged[mod]
        parts = []
        if default:
            parts.append(default)
        if named:
            parts.append('{ ' + ', '.join(sorted(named)) + ' }')
        lines.append(f"import {', '.join(parts)} from '{mod}';")
    return '\n'.join(lines) + '\n'


lib_imports, lib_body = split_imports(open(lib_path).read())
count = 0
for name in sorted(os.listdir(src_dir)):
    if not name.endswith('.js'):
        continue
    src_imports, src_body = split_imports(open(os.path.join(src_dir, name)).read())
    src_imports = [(w, m) for (w, m) in src_imports if not m.endswith('lib/ipam-client.js')]
    header = (
        "// Code generated by hack/bundle-k6.sh. DO NOT EDIT.\n"
        f"// Source: test/load/src/{name}\n"
        "// Lib:    test/load/lib/ipam-client.js\n\n"
    )
    with open(os.path.join(dest_dir, name), 'w') as f:
        f.write(header)
        f.write(render(merge(lib_imports + src_imports)))
        f.write('\n// ---- test/load/lib/ipam-client.js ----\n')
        f.write(lib_body)
        f.write(f'\n// ---- test/load/src/{name} ----\n')
        f.write(src_body)
    print(f"  ok  {name}")
    count += 1

print(f"\nGenerated {count} bundled k6 scripts in {dest_dir}")
PY
